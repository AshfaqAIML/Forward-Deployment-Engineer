// src/ai/tutor.js — the grounded tutor prompts. The approved curriculum is
// the ONLY content source; the system prompt enforces citation, refusal
// outside the material, and the educational/verified distinction.
import { retrieve } from "./retriever.js";

const BASE_RULES = `You are the optional AI tutor of FDE Academy, helping a learner work through the approved course material.

HARD RULES (non-negotiable):
1. Ground every content claim in the MATERIAL section. If the material does not cover what is asked, reply starting with "This is not covered in the approved course material." and stop; you may add at most one sentence suggesting which cited lesson to revisit.
2. NEVER invent lesson content, quiz questions, correct answers, scores, or completion records. Never state or imply the learner completed anything.
3. When you rely on the material, cite it inline with its tag, e.g. [lesson:fm-1] or [glossary:break-even].
4. Distinguish clearly: sentences summarising the cited material are educational explanations of verified material. Anything beyond the material must carry the prefix "Outside the course material:" — used sparingly.
5. Style: warm, concrete, example-first, short paragraphs. Match the material's tone (market stalls, bread rolls, wages, networks).`;

const MODES = {
  explain: "TASK: Explain the learner's question in simpler words, using ONLY the material provided. Prefer one concrete worked example from the material.",
  vocabulary: "TASK: Explain the technical vocabulary the learner asks about, using the glossary material provided. Give the plain meaning first, then the precise one, then the material's own example.",
  examples: "TASK: Give ONE additional worked example in the spirit of the material. Base every quantity and rule on the material; say where each number comes from.",
  practice: "TASK: Generate the requested number of practice questions in the style of the material. Prefix the whole set with: 'PRACTICE — generated by the AI tutor, not verified course material.' Provide an answer key at the end. Never present these as official knowledge checks.",
  hint: "TASK: Give ONE progressive hint toward the exercise, WITHOUT revealing the full solution. Base it on the exercise instructions and starter code provided.",
  error: "TASK: Help the learner understand a programming error they hit while working on the exercise. Identify what the error means, why their code triggers it (quote their line if visible), and the smallest fix. Base the explanation on the exercise's language and intent.",
  math: "TASK: Walk through the mathematical steps, one line at a time, in the material's style (money in / money out tables, per-item first). State each step in words then in numbers. Base formulas ONLY on the material; if the material lacks the needed rule, apply rule 1.",
};

export const DISCLAIMER = "AI tutor explanations are educational support generated from the approved FDE Academy material — they are not verified course content and are never recorded as results. Verified material is listed under sources.";

export async function tutorAnswer(db, provider, { mode = "explain", message, lessonCode, extra = "" }) {
  const normMode = MODES[mode] ? mode : "explain";
  const retrieval = await retrieve(db, message || "", { lessonCode });
  const system = [
    BASE_RULES,
    `MODE: ${normMode}`,
    retrieval.material ? "MATERIAL BEGINS" : "MATERIAL IS EMPTY — rule 1 applies to the whole answer.",
    retrieval.material || "",
    "MATERIAL ENDS",
  ].join("\n\n");
  const user = [message, extra].filter(Boolean).join("\n\n");
  const answer = await provider.complete(system, user);
  return {
    mode: normMode,
    answer,
    sources: retrieval.sources,
    grounded: retrieval.grounded,
    disclaimer: DISCLAIMER,
  };
}

// Progressive hints: authored hints first (deterministic), AI fallback beyond
// the authored set — always grounded in the exercise.
export async function progressiveHint(db, provider, { exerciseCode, hintIndex }) {
  const ex = await db.query(
    `SELECT id, code, title, language, instructions, starter_code FROM coding_exercises
     WHERE (code = $1 OR id::text = $1) AND status = 'published'`, [String(exerciseCode)]);
  const exercise = ex.rows[0];
  if (!exercise) return null;
  const hints = await db.query(
    `SELECT position, content FROM exercise_hints WHERE owner_type = 'coding_exercise' AND owner_id = $1 ORDER BY position`,
    [exercise.id]);
  const authored = hints.rows;
  const idx = Math.max(1, parseInt(hintIndex || "1", 10) || 1);
  if (idx <= authored.length) {
    return { exerciseCode: exercise.code, hintIndex: idx, authored: true, hint: authored[idx - 1].content,
      totalAuthored: authored.length, disclaimer: DISCLAIMER };
  }
  const result = await tutorAnswer(db, provider, {
    mode: "hint",
    message: `Give progressive hint #${idx} (all ${authored.length} authored hints have been seen: ${authored.map(h => h.content).join(" | ")}) for the exercise "${exercise.title}".`,
    extra: `Exercise instructions: ${exercise.instructions}\nStarter code:\n${exercise.starter_code}`,
  });
  return { exerciseCode: exercise.code, hintIndex: idx, authored: false, hint: result.answer,
    totalAuthored: authored.length, disclaimer: DISCLAIMER };
}

export async function generatePractice(db, provider, { lessonCode, count = 3 }) {
  const n = Math.min(6, Math.max(1, parseInt(count, 10) || 3));
  const result = await tutorAnswer(db, provider, {
    mode: "practice",
    message: `Generate ${n} practice questions on this lesson.`,
    lessonCode,
  });
  return { ...result, practice: true, count: n,
    note: "Practice questions generated by the AI tutor. They are NOT official knowledge checks, are never scored, and never affect progress." };
}
