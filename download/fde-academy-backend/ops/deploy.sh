#!/usr/bin/env bash
# ops/deploy.sh — bring up a production-style deployment of FDE Academy.
#
#   ./ops/deploy.sh            # first install or after content changes
#   ./ops/deploy.sh --restart  # just (re)start the server
#
# What it does:
#   1. generates FDE_JWT_SECRET once into .env (gitignored — never committed)
#   2. applies all migrations to the file-backed PostgreSQL (PGlite)
#   3. seeds the approved curriculum and books
#   4. (optional) publishes the print editions — run the book pipeline's
#      publish.py --base http://127.0.0.1:8787 after this script
#   5. starts the server: one process serves the website AND the API
#
# For a hosted production deployment see docs/DEPLOYMENT.md (NODE_ENV=
# production, external PostgreSQL via DATABASE_URL, no demo users).
set -euo pipefail
cd "$(dirname "$0")/.."

# ---- environment (.env is generated once; it holds a secret, never commit it) ----
if [ ! -f .env ]; then
  umask 077
  {
    echo "# Generated by ops/deploy.sh — LOCAL SECRETS. Do not commit."
    echo "FDE_JWT_SECRET=$(openssl rand -hex 48)"
    echo "FDE_PORT=8787"
    echo "FDE_HOST=127.0.0.1"
    echo "FDE_PGLITE_DIR=pgdata"
    echo "FDE_STORAGE_DIR=storage"
    echo "FDE_LOG_LEVEL=info"
    echo "FDE_SEED_DEMO_USERS=1"
    echo "FDE_DEMO_PASSWORD=$(openssl rand -base64 12 | tr -d '/+=')"
  } > .env
  echo "[deploy] generated .env with a fresh JWT secret (gitignored)"
  echo "[deploy] demo sign-in (sandbox only): admin@fde.local / $(grep FDE_DEMO_PASSWORD .env | cut -d= -f2)"
  echo "[deploy] NOTE: real production must run without FDE_SEED_DEMO_USERS (see docs/DEPLOYMENT.md)"
fi
set -a; . ./.env; set +a

if [ "${1:-}" = "--restart" ]; then
  exec node src/server.js
fi

echo "[deploy] 1/3 migrations (embedded PostgreSQL at ${FDE_PGLITE_DIR:-pgdata})"
node src/db/migrate.js up

echo "[deploy] 2/3 seed curriculum + books + demo users"
node src/db/seed.js

echo "[deploy] 3/3 starting server on ${FDE_HOST:-127.0.0.1}:${FDE_PORT:-8787}"
echo "[deploy] website:      http://${FDE_HOST:-127.0.0.1}:${FDE_PORT:-8787}/"
echo "[deploy] health check: http://${FDE_HOST:-127.0.0.1}:${FDE_PORT:-8787}/api/v1/health"
exec node src/server.js
