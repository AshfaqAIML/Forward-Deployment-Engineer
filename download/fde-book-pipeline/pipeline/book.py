"""book.py — assembles a complete print edition from the approved corpus:

cover → edition page → contents (two-pass, real page numbers) → how to use →
chapters (page-break-separated, full frame) → glossary → references → answer
key → colophon. Headers/footers and restarted page numbering on the body.
"""
import os
from datetime import date

from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_TAB_ALIGNMENT, WD_TAB_LEADER
from docx.enum.section import WD_SECTION
from docx.oxml.ns import qn

from .chapter import Chapter, build_chapter
from .figures import cover_figure
from .styles import (NAVY, TEAL, MUTED, HEAD_FONT, BODY_FONT, styled_table,
                     restart_page_numbering, field_run, keep_with_next)

BACK_MATTER = ["Glossary", "References", "Answer key"]


def _front_title(doc, text, size=26):
    p = doc.add_paragraph(style=doc.styles["FDE FrontTitle"])
    p.add_run(text)
    return p


def _meta(doc, text):
    return doc.add_paragraph(text, style=doc.styles["FDE Meta"])


def _body_section(doc, book):
    """Start the body: new section, header/footer, page numbers from 1."""
    sec = doc.add_section(WD_SECTION.NEW_PAGE)
    sec.page_width, sec.page_height = doc.sections[0].page_width, doc.sections[0].page_height
    for k in ("top", "bottom", "left", "right"):
        setattr(sec, f"{k}_margin", getattr(doc.sections[0], f"{k}_margin"))
    restart_page_numbering(sec, 1)
    # header: book title left, subject right — UNLINK first, or the new
    # section's header writes through to the cover section
    h = sec.header
    h.is_linked_to_previous = False
    hp = h.paragraphs[0]
    hp.style = doc.styles["FDE Meta"]
    hp.paragraph_format.tab_stops.add_tab_stop(Cm(16.2), WD_TAB_ALIGNMENT.RIGHT)
    r = hp.add_run(book["title"])
    r.font.name = HEAD_FONT; r.font.size = Pt(8.2)
    r.font.color.rgb = RGBColor.from_string(NAVY)
    r2 = hp.add_run(f"\t{book['subject']} · FDE Academy print edition")
    r2.font.name = HEAD_FONT; r2.font.size = Pt(8.2)
    r2.font.color.rgb = RGBColor.from_string(MUTED)
    pb = hp.paragraph_format
    pb.space_after = Pt(2)
    # footer: centered page number + edition line
    f = sec.footer
    f.is_linked_to_previous = False
    fp = f.paragraphs[0]
    fp.style = doc.styles["FDE Meta"]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rl = fp.add_run(f"{book['title']} · v{book['version']} · page ")
    rl.font.size = Pt(8.2); rl.font.name = HEAD_FONT
    rl.font.color.rgb = RGBColor.from_string(MUTED)
    field_run(fp, "PAGE")
    return sec


def build_book(doc, book, data, toc_pages=None):
    """Build the whole book. toc_pages: None → placeholder numbers (pass 1);
    a dict label→page → real numbers (pass 2). Returns build stats."""
    stats = {"chapters": [], "tocEntries": [], "figures": 0, "tables": 0,
             "equations": 0, "code": 0}
    answer_key = {"exercises": [], "reviews": []}

    # ================= cover (section 1, no header/footer) =================
    cover_path = cover_figure(book)
    doc.add_picture(cover_path, width=Cm(16.2))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER

    # ================= edition / imprint page =================
    sec2 = _body_section(doc, book)
    ep = doc.add_paragraph("", style=doc.styles["FDE Meta"])
    _front_title(doc, book["title"], 22)
    _meta(doc, f"{book['subject']} series · Print edition {book['edition']} · Version {book['version']}")
    _meta(doc, f"Identifier {book['identifier']} · Published {book['publicationDate']} · Difficulty {book.get('difficulty', 'Beginner')}")
    _meta(doc, "")
    dp = doc.add_paragraph(book.get("description", ""), style="FDE Body")
    _meta(doc, "")
    # outcomes table
    if book.get("objectives"):
        keep_with_next(doc.add_paragraph("What this book delivers", style=doc.styles["FDE H3"]))
        styled_table(doc, ["By the end of this book you can"], [[o] for o in book["objectives"]],
                     widths=[16.2])
    _meta(doc, "")
    _meta(doc, "© FDE Academy. This print edition is generated from the approved "
               "curriculum of the FDE Academy platform and carries the same content as the "
               "online lessons it collects. Educational use is licensed to enrolled students.")
    _meta(doc, f"Generated by the FDE Academy book pipeline · build {date.today().isoformat()}")

    # ================= contents (two-pass) =================
    ch_labels = [f"Chapter {i} · {c.title}" for i, c in enumerate(data.chapters, 1)]
    entries = ["Contents"] + ch_labels + BACK_MATTER
    tp = doc.add_paragraph("", style=doc.styles["FDE Meta"])
    add_page_break = tp.paragraph_format.page_break_before = True
    th = doc.add_paragraph(style=doc.styles["FDE FrontTitle"])
    th.paragraph_format.page_break_before = True
    th.add_run("Contents")
    for i, label in enumerate(entries[1:], 1):
        is_chapter = label.startswith("Chapter")
        p = doc.add_paragraph(style=doc.styles["FDE TOC1" if is_chapter else "FDE TOC2"])
        p.paragraph_format.tab_stops.add_tab_stop(Cm(16.2), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        if toc_pages:
            page = toc_pages.get(label, "")
        else:
            page = "0" * max(1, len(str(60 - i)))  # pass-1 placeholder keeps layout stable
        r = p.add_run(label)
        if is_chapter:
            r.font.name = HEAD_FONT
        p.add_run(f"\t{page}")
        stats["tocEntries"].append(label)
    # teach the reader how the book works
    hu = doc.add_paragraph(style=doc.styles["FDE H2"])
    hu.paragraph_format.page_break_before = True
    hu.add_run("How to use this book")
    for line in book.get("howToUse", [
        "Read a chapter from beginning to end before attempting its exercises.",
        "The Learning objectives box tells you exactly what you should be able to do afterwards.",
        "Worked examples show a full solution; Exercises leave the answer to the Answer key at the back.",
        "Review questions mirror the platform knowledge checks — answer them before moving on.",
        "The Glossary collects every technical term used in this book; terms are cited from the platform curriculum.",
    ]):
        p = doc.add_paragraph(style=doc.styles["FDE ListItem"])
        p.paragraph_format.left_indent = Cm(0.6)
        rr = p.add_run("•  ")
        rr.font.color.rgb = RGBColor.from_string(TEAL)
        p.add_run(line)

    # ================= chapters =================
    for i, ch in enumerate(data.chapters, 1):
        build_chapter(doc, ch, data, answer_key)
        stats["chapters"].append({"number": i, "title": ch.title, "code": ch.code, **ch.stats})
        stats["figures"] += ch.stats["figures"]
        stats["tables"] += ch.stats["tables"]
        stats["equations"] += ch.stats["equations"]
        stats["code"] += ch.stats["code"]

    # ================= glossary =================
    gh = doc.add_paragraph(style=doc.styles["FDE H1"])
    gh.paragraph_format.page_break_before = True
    gh.add_run("Glossary")
    terms = data.glossary()
    rows = [[t["term"], t["simple"]] for t in terms]
    styled_table(doc, ["Term", "Meaning (as used in the course)"], rows,
                 widths=[4.6, 11.6])

    # ================= references =================
    rh = doc.add_paragraph(style=doc.styles["FDE H1"])
    rh.paragraph_format.page_break_before = True
    rh.add_run("References")
    for i, ref in enumerate(data.references, 1):
        p = doc.add_paragraph(style=doc.styles["FDE ListItem"])
        rr = p.add_run(f"[{i}]  ")
        rr.font.bold = True; rr.font.color.rgb = RGBColor.from_string(NAVY)
        p.add_run(ref["text"])
        if ref.get("url"):
            ru = p.add_run(f"  — {ref['url']}")
            ru.font.color.rgb = RGBColor.from_string(TEAL)
            ru.font.size = Pt(8.8)

    # ================= answer key =================
    ah = doc.add_paragraph(style=doc.styles["FDE H1"])
    ah.paragraph_format.page_break_before = True
    ah.add_run("Answer key")
    _meta(doc, "Check your work only after a genuine attempt — the answers are "
               "the last step of studying, not the first.")
    cur = 0
    for item in answer_key["reviews"]:
        if item["chapter"] != cur:
            cur = item["chapter"]
            chh = doc.add_paragraph(style=doc.styles["FDE H3"])
            chh.add_run(f"Chapter {cur}")
        p = doc.add_paragraph(style=doc.styles["FDE ListItem"])
        p.paragraph_format.left_indent = Cm(0.6)
        r1 = p.add_run(f"{item['n']}.  ")
        r1.font.bold = True
        p.add_run(item["answer"])
        if item.get("explanation"):
            p2 = doc.add_paragraph(style=doc.styles["FDE Meta"])
            p2.paragraph_format.left_indent = Cm(1.0)
            p2.add_run("Why: " + item["explanation"])
    cur = 0
    for item in answer_key["exercises"]:
        if not item.get("solution"):
            continue
        if item["chapter"] != cur:
            cur = item["chapter"]
            chh = doc.add_paragraph(style=doc.styles["FDE H3"])
            chh.add_run(f"Chapter {cur} — exercises")
        p = doc.add_paragraph(style=doc.styles["FDE ListItem"])
        p.paragraph_format.left_indent = Cm(0.6)
        r1 = p.add_run(f"{item['n']}.  ")
        r1.font.bold = True
        p.add_run(item["solution"])

    # ================= colophon =================
    co = doc.add_paragraph(style=doc.styles["FDE Meta"])
    co.paragraph_format.page_break_before = True
    co.alignment = WD_ALIGN_PARAGRAPH.CENTER
    co.add_run(f"FDE Academy · {book['title']} · {book['edition']} edition · "
               f"version {book['version']} · {book['publicationDate']}\n"
               f"Identifier {book['identifier']} · Produced by the FDE Academy "
               f"book production pipeline (DOCX + PDF from one approved source).")

    stats["answerKey"] = {"reviews": len(answer_key["reviews"]),
                          "exercises": len(answer_key["exercises"])}
    return stats
