#!/usr/bin/env python3
"""publish.py — website integration: make the finished print editions
available through the FDE Academy book library.

For every book that PASSED the QC gate (reports/<slug>.qc.json):
  1. upload the DOCX and PDF as private book files
  2. attach each as a book edition (version, format)
  3. verify the library serves correct book info + working download links

Refuses to publish a book whose QC did not pass — no unfinished releases.
"""
import argparse
import glob
import json
import os
import sys
import urllib.request
import urllib.error

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
from pipeline.data import load  # noqa: E402


def api(base, token, method, path, body=None, raw=None):
    req = urllib.request.Request(base + path, method=method)
    if token:
        req.add_header("authorization", "Bearer " + token)
    data = None
    if raw is not None:
        data = raw
    elif body is not None:
        req.add_header("content-type", "application/json")
        data = json.dumps(body).encode()
    try:
        with urllib.request.urlopen(req, data) as res:
            return res.status, json.loads(res.read().decode() or "{}")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read().decode() or "{}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://127.0.0.1:8908")
    ap.add_argument("--email", default="admin@fde.local")
    ap.add_argument("--password", default=os.environ.get("FDE_DEMO_PASSWORD", "DemoPass-2026"))
    args = ap.parse_args()

    _, st = api(args.base, None, "GET", "/api/v1/ai/tutor/status")
    if not st.get("enabled") and "error" in st:
        print("server not reachable:", st)
        sys.exit(2)

    status, login = api(args.base, None, "POST", "/api/v1/auth/login",
                        body={"email": args.email, "password": args.password})
    assert status == 200, f"login failed: {login}"
    token = login["accessToken"]

    results = []
    for slug in ("fm", "alg", "log", "gph", "ps", "hb"):
        spec, data = load(slug)
        qc_path = os.path.join(ROOT, "reports", f"{slug}.qc.json")
        qc = json.load(open(qc_path)) if os.path.exists(qc_path) else {"passed": False}
        if not qc.get("passed"):
            print(f"SKIP {slug}: QC gate not passed — not publishing an unapproved book")
            results.append((slug, "skipped-unapproved"))
            continue

        _, detail = api(args.base, token, "GET", f"/api/v1/books/{spec['slug']}")
        if "error" in detail:
            print(f"SKIP {slug}: book not in library ({detail['error']['message']})")
            results.append((slug, "missing-in-library"))
            continue
        book_id = detail["book"]["id"]

        added = []
        for fmt in ("docx", "pdf"):
            fpath = os.path.join(ROOT, "dist", f"{data.filename()}.{fmt}")
            assert os.path.exists(fpath), fpath
            fname = os.path.basename(fpath)
            # 1. upload as a private book file (octet-stream)
            req = urllib.request.Request(
                args.base + f"/api/v1/admin/cms/uploads?kind=book&filename={fname}",
                method="POST", data=open(fpath, "rb").read())
            req.add_header("authorization", "Bearer " + token)
            with urllib.request.urlopen(req) as res:
                f = json.loads(res.read().decode())
            # 2. attach as an edition
            st2, ed = api(args.base, token, "POST",
                          f"/api/v1/admin/cms/books/{book_id}/editions",
                          body={"version": spec["version"], "format": fmt,
                                "fileId": f["id"], "notes": "Print edition generated by the book pipeline"})
            assert st2 == 201, (st2, ed)
            added.append(fmt)

        # 3. verify: library shows the editions and the downloads work
        _, after = api(args.base, token, "GET", f"/api/v1/books/{slug}")
        formats = [e["format"] for e in after["editions"]]
        has_both = "docx" in formats and "pdf" in formats
        dl_status = None
        _, issued = api(args.base, token, "POST", f"/api/v1/books/{slug}/downloads", body={})
        if issued.get("downloadUrl"):
            req = urllib.request.Request(args.base + issued["downloadUrl"])
            req.add_header("authorization", "Bearer " + token)
            with urllib.request.urlopen(req) as res:
                dl_status = res.status
                dl_size = len(res.read())
        else:
            dl_size = 0
        ok = has_both and dl_status == 200 and dl_size > 50_000
        results.append((slug, "published" if ok else f"verify-failed({dl_status},{dl_size})"))
        print(f"{'PASS' if ok else 'FAIL'} {slug}: editions={formats} download={dl_status} ({dl_size} bytes)")

    print("\nPublish summary:", dict(results))
    if any(v != "published" for _, v in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
